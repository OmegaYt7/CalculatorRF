// ============================================================
// errors.js — два вида ожидаемых ошибок калькулятора.
// Всё остальное (обычный Error) считается «сбоем в ходе выполнения».
// ============================================================
(function () {
  const LA = (window.LA = window.LA || {}); // общий «ящик» (пространство имён) для всех файлов

  // Операция математически невозможна (например, сложить матрицы разных размеров)
  class MathError extends Error {}

  // Пользователь неверно ввёл данные (пустая клетка, буквы вместо числа)
  class InputError extends Error {}

  LA.MathError = MathError;
  LA.InputError = InputError;
})();
